'use strict';

const assert = require('node:assert/strict');
const childProcess = require('node:child_process');
const path = require('node:path');

const database = process.env.MCP_LOCAL_TEST_DATABASE || '';
const port = Number(process.env.MCP_LOCAL_TEST_PORT || '');
const psql = process.env.MCP_LOCAL_TEST_PSQL || '';
assert.match(database, /^mcp_local_[0-9a-f]{16}$/i, 'database name must be generated by the local runner');
assert.ok(Number.isInteger(port) && port >= 1024 && port <= 65535, 'explicit loopback PostgreSQL port is required');
assert.ok(path.isAbsolute(psql), 'set MCP_LOCAL_TEST_PSQL to an absolute local psql executable path');

function args(databaseName, extra = []) {
  assert.match(databaseName, /^(postgres|mcp_local_[0-9a-f]{16})$/i, 'database name is outside the local test allowlist');
  return ['-X', '-h', '127.0.0.1', '-p', String(port), '-U', 'postgres', '-d', databaseName, '-w', '-v', 'ON_ERROR_STOP=1', ...extra];
}

function run(databaseName, extra = [], input) {
  const result = childProcess.spawnSync(psql, args(databaseName, extra), {
    encoding: 'utf8',
    input,
    windowsHide: true,
    shell: false,
  });
  if (result.status !== 0) {
    throw new Error((result.stderr || result.stdout || String(result.error)).slice(-6000));
  }
  return result.stdout.trim();
}

module.exports = { args, database, port, psql, run };
